    'A source object''s msDS-AllowedToDelegateTo lists an SPN that does '
    'not resolve to any currently-collected object ("ghost SPN") -- a '
    'pre-staging/decommissioning artifact an attacker could exploit by '
    'registering a matching SPN themselves. Kept separate from '
    'delegation_edge deliberately -- see this migration''s own header '
