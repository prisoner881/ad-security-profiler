--      baked in partitions for whatever specific months existed at
--      dump time -- meaningless (and actively wrong) for a deployment
--      starting at some future, unrelated date.
--   4. partitioned_table_registry's rows were re-added by hand: this
--      is DATA, not schema, so --schema-only correctly excluded it,
--      but ensure_partitions_for_horizon() needs it populated to
--      create any partitions at all.
--   5. A call to ensure_partitions_for_horizon(2) was added at the
--      end, so partitions get created relative to whenever THIS
--      script actually runs, not frozen at generation time.
--   6. upsert_directory_object() and set_current_version() were
--      inserted by hand, copied verbatim from the real schema.sql.
--      These use PostgreSQL 17's MERGE...RETURNING syntax, which the
--      database this dump was generated from could not execute (it
--      ran on PG16, this sandbox's only available version) -- so a
--      naive dump would have captured empty placeholder stubs instead
--      of the genuine functions. Caught by checking for their
--      presence explicitly rather than assuming pg_dump captured
--      everything needed.
--
