--
-- Name: upsert_directory_object; Type: FUNCTION; Schema: ad_intel; Owner: -
-- [Consolidated manually from schema.sql -- genuine PostgreSQL 17
--  MERGE...RETURNING syntax. The pg_dump this file was built from came
--  from a PG16 test database using placeholder stubs for this function
--  (PG16 cannot even parse MERGE...RETURNING), so it had to be inserted
--  here by hand rather than captured by the dump itself.]
--

CREATE OR REPLACE FUNCTION ad_intel.upsert_directory_object(
    p_object_guid       UUID,
    p_client_id         UUID,
    p_object_sid        TEXT,
    p_dn                TEXT,
    p_object_class      ad_intel.ad_object_class,
    p_sam_account_name  TEXT,
    p_run_id            BIGINT
) RETURNS TABLE (action TEXT, object_guid UUID) AS $$
    MERGE INTO ad_intel.directory_object AS d
    USING (SELECT p_object_guid AS object_guid) AS src
    ON d.object_guid = src.object_guid
    WHEN MATCHED THEN
        UPDATE SET dn_current            = p_dn,
                   object_sid            = p_object_sid,
                   sam_account_name      = p_sam_account_name,
                   last_confirmed_run_id = p_run_id
    WHEN NOT MATCHED THEN
        INSERT (object_guid, client_id, object_sid, dn_current, object_class,
                sam_account_name, first_seen_run_id, last_confirmed_run_id)
        VALUES (p_object_guid, p_client_id, p_object_sid, p_dn, p_object_class,
                p_sam_account_name, p_run_id, p_run_id)
    RETURNING merge_action(), d.object_guid;
$$ LANGUAGE sql;

COMMENT ON FUNCTION ad_intel.upsert_directory_object IS
    'PG17 MERGE...RETURNING upsert. Returns action = ''INSERT'' or ''UPDATE'' '
    'per call so the collector loader can tally new-vs-confirmed objects '
    'without a separate lookup query.';

