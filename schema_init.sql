-- Ghost SPN constrained delegation (Purple Knight-inspired)
--
-- delegation_edge itself was checked before adding a new table here:
-- its own check constraint (delegation_edge_check1) only permits a
-- NULL target_guid for delegation_type = 'unconstrained', and
-- target_guid's FK requires any non-null value to reference a real
-- directory_object row -- neither can represent "a constrained
-- delegation target SPN that doesn't resolve to anything," so this is
-- a dedicated table rather than a workaround bolted onto an already
-- deliberately-constrained one.
-- ---------------------------------------------------------------------
CREATE TABLE unresolved_delegation_target_edge (
    edge_id             BIGINT NOT NULL,
    client_id           UUID NOT NULL,
    source_guid         UUID NOT NULL,
    target_spn          TEXT NOT NULL,
    valid_from          TIMESTAMPTZ NOT NULL,
    valid_to            TIMESTAMPTZ,
    run_id_valid_from   BIGINT NOT NULL,
    run_id_valid_to     BIGINT,
    PRIMARY KEY (edge_id, valid_from),
    CHECK (valid_to IS NULL OR valid_to > valid_from),
    FOREIGN KEY (source_guid, client_id) REFERENCES directory_object(object_guid, client_id) ON DELETE RESTRICT,
    FOREIGN KEY (run_id_valid_from, client_id) REFERENCES sync_run(run_id, client_id) ON DELETE RESTRICT,
    FOREIGN KEY (run_id_valid_to, client_id) REFERENCES sync_run(run_id, client_id) ON DELETE RESTRICT
);
