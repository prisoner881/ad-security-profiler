-- HOW THIS WAS BUILT
--   1. A fresh database was built from schema.sql + all 27 migrations,
--      in order, and confirmed to apply with zero errors.
--   2. `pg_dump --schema-only` captured that database's final
--      structure -- tables, types, functions, indexes, constraints.
--   3. Every dated, concrete partition table/index generated by
--      ensure_partitions_for_horizon() calls made DURING TESTING
