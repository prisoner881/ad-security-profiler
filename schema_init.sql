-- Name: create_monthly_partition(text, date); Type: FUNCTION; Schema: ad_intel; Owner: -
--

CREATE FUNCTION ad_intel.create_monthly_partition(p_table text, p_month date) RETURNS void
    LANGUAGE plpgsql
    AS $$
DECLARE
    v_start   DATE := date_trunc('month', p_month);
    v_end     DATE := v_start + INTERVAL '1 month';
    v_part    TEXT := format('%s_%s', p_table, to_char(v_start, 'YYYY_MM'));
    v_high_churn BOOLEAN;
BEGIN
    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS ad_intel.%I PARTITION OF ad_intel.%I
             FOR VALUES FROM (%L) TO (%L)',
        v_part, p_table, v_start, v_end
    );

    SELECT high_churn INTO v_high_churn
    FROM partitioned_table_registry WHERE table_name = p_table;

    IF v_high_churn THEN
        EXECUTE format(
            'ALTER TABLE ad_intel.%I SET (autovacuum_vacuum_scale_factor = 0.02,
                                           autovacuum_analyze_scale_factor = 0.02)',
            v_part
        );
    END IF;
END;
$$;


--
-- Name: drop_partitions_older_than(text, integer); Type: FUNCTION; Schema: ad_intel; Owner: -
--

CREATE FUNCTION ad_intel.drop_partitions_older_than(p_table text, p_retention_months integer DEFAULT 12) RETURNS void
    LANGUAGE plpgsql
    AS $_$
DECLARE
    v_cutoff   DATE := date_trunc('month', now())::date - (p_retention_months || ' month')::interval;
    v_rec      RECORD;
BEGIN
    FOR v_rec IN
        SELECT c.relname AS partition_name
        FROM pg_inherits i
        JOIN pg_class c       ON c.oid = i.inhrelid
        JOIN pg_class parent  ON parent.oid = i.inhparent
        WHERE parent.relname = p_table
          AND c.relname ~ '_\d{4}_\d{2}$'
          AND to_date(right(c.relname, 7), 'YYYY_MM') < v_cutoff
    LOOP
        EXECUTE format('DROP TABLE IF EXISTS ad_intel.%I', v_rec.partition_name);
        RAISE NOTICE 'Dropped partition % (older than % months)', v_rec.partition_name, p_retention_months;
    END LOOP;
END;
$_$;


--
-- Name: ensure_partitions_for_horizon(integer); Type: FUNCTION; Schema: ad_intel; Owner: -
--

CREATE FUNCTION ad_intel.ensure_partitions_for_horizon(p_months_ahead integer DEFAULT 2) RETURNS void
    LANGUAGE plpgsql
    AS $$
DECLARE
    v_table   TEXT;
    v_month   DATE;
BEGIN
    FOR v_table IN SELECT table_name FROM partitioned_table_registry LOOP
        FOR v_month IN
            SELECT date_trunc('month', now())::date + (n || ' month')::interval
            FROM generate_series(0, p_months_ahead) AS n
        LOOP
            PERFORM create_monthly_partition(v_table, v_month::date);
        END LOOP;
    END LOOP;
END;
$$;


--
-- Name: run_partition_maintenance(); Type: FUNCTION; Schema: ad_intel; Owner: -
--

CREATE FUNCTION ad_intel.run_partition_maintenance() RETURNS void
    LANGUAGE plpgsql
    AS $$
DECLARE
    v_table TEXT;
BEGIN
    PERFORM ensure_partitions_for_horizon(2);
    FOR v_table IN SELECT table_name FROM partitioned_table_registry LOOP
        PERFORM drop_partitions_older_than(v_table, 12);
    END LOOP;
END;
$$;


